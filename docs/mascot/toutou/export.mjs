// 投投 final exports.  node docs/mascot/toutou/export.mjs   (headless Chrome + Node only; nothing on screen)
//   video/res/toutou/*.png + toutou_layout.h   layers embedded in the app (see video/src/ui_art.*)
//   app/res/app.ico                            16 20 24 32 40 48 64 256, PNG entries, each size hand-tuned
//   assets/public/toutou/                      expressions, layers, per-theme phones, masters, icons, SVG
//   docs/mascot/toutou/final.png               reference sheet
// After a re-export, shrink the embedded layers losslessly (0.7.8: -29%, pixels identical) and
// re-copy them to assets/public/toutou/layers/:  oxipng -o max --strip all -Z video/res/toutou/*.png
import { mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { hero, layer, monitor, phoneSvg, MOODS, THEMES, PHONE, CANVAS, TILT, PIVOT, beamSvg, phoneTop } from './hero.mjs';
import { iconSvg, ICON_SIZES } from './icon.mjs';
import { renderHtml, page, svgUri } from './render.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(here, '../../..');
const RES = join(ROOT, 'video/res/toutou');
const PUB = join(ROOT, 'assets/public/toutou');
for (const d of [RES, PUB, join(PUB, 'layers'), join(PUB, 'svg'), join(PUB, 'icon')]) mkdirSync(d, { recursive: true });

const SCALE = 4; // px per frame unit for the app layers (cloud ~630 px wide)
const W = Math.round(CANVAS.w * SCALE), H = Math.round(CANVAS.h * SCALE);
const vb = `${CANVAS.x} ${CANVAS.y} ${CANVAS.w} ${CANVAS.h}`;
const doc = (viewBox, inner, w, h) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}"${w ? ` width="${w}" height="${h}"` : ''}>${inner}</svg>`;
const png = (svg, out, w, h) => renderHtml(page(svg.replace('<svg ', `<svg style="display:block" `)), out, w, h, 1);

// ---------------------------------------------------------------- app layers
const FACES = MOODS; // idle blink happy connecting surprised sleepy asleep
const POSES = Object.keys(PHONE);
png(doc(vb, layer.cloud(), W, H), join(RES, 'cloud.png'), W, H);
png(doc(vb, layer.rim(), W, H), join(RES, 'rim.png'), W, H);
for (const m of FACES) png(doc(vb, layer.face(m), W, H), join(RES, `face_${m}.png`), W, H);
for (const p of POSES) png(doc(vb, layer.hand(p), W, H), join(RES, `hand_${p}.png`), W, H);

const fl = (v) => (Number.isInteger(v) ? `${v}.f` : `${v}f`);
const poseLine = (n, P) => `    {${fl(P.x)}, ${fl(P.y)}, ${fl(P.w)}, ${fl(P.h)}, ${fl(P.rot)}},  // ${n}`;
writeFileSync(join(RES, 'toutou_layout.h'), `// Generated by docs/mascot/toutou/export.mjs - do not edit.
// 投投 layer geometry in the art's frame units (layers cover kCanvas; the character is tilted kTilt degrees
// around kPivot, which is also the squash / stretch pivot = bottom centre of the cloud).
#pragma once
namespace pm::video::toutou {
struct Rect { float x, y, w, h; };
struct Phone { float x, y, w, h, rot; };  // centre, size, rotation (deg), before the tilt
constexpr Rect kCanvas{${CANVAS.x}.f, ${CANVAS.y}.f, ${CANVAS.w}.f, ${CANVAS.h}.f};
constexpr float kTilt = ${TILT}.f;
constexpr float kPivotX = ${PIVOT[0]}.f, kPivotY = ${PIVOT[1]}.f;
// Cloud extent (for layout): left, top, right, bottom of the body silhouette.
constexpr Rect kBody{54.f, 50.f, 158.f, 116.f};
enum Pose { kHold, kSleepy, kAsleep };
constexpr Phone kPhone[3] = {
${POSES.map((p) => poseLine(p, PHONE[p])).join('\n')}
};
constexpr float kPhoneRadius = 7.f, kPhoneBezel = 2.6f;
constexpr float kLayerScale = ${SCALE}.f;  // layer pixels per frame unit
}  // namespace pm::video::toutou
`);

// ---------------------------------------------------------------- public assets
const S = THEMES.Sakura;
const EXPR_VB = '34 18 222 190';
for (const m of MOODS) {
  const svg = doc(EXPR_VB, hero({ mood: m, accent: S.accent }));
  writeFileSync(join(PUB, 'svg', `toutou_${m}.svg`), svg);
  png(doc(EXPR_VB, hero({ mood: m, accent: S.accent }), 666, 570), join(PUB, `toutou_${m}.png`), 666, 570);
}
// layers (same as the app's) + phone per theme
for (const f of ['cloud', 'rim', ...FACES.map((m) => `face_${m}`), ...POSES.map((p) => `hand_${p}`)])
  writeFileSync(join(PUB, 'layers', `${f}.png`), readFileSync(join(RES, `${f}.png`)));
const PV = '186 92 72 72';
for (const [t, th] of Object.entries(THEMES)) {
  png(doc(PV, `<g transform="rotate(${TILT} ${PIVOT[0]} ${PIVOT[1]})">${phoneSvg('hold', th.accent, true)}</g>`, 216, 216), join(PUB, 'layers', `phone_${t}.png`), 216, 216);
}
png(doc(PV, `<g transform="rotate(${TILT} ${PIVOT[0]} ${PIVOT[1]})">${phoneSvg('hold', S.accent, false)}</g>`, 216, 216), join(PUB, 'layers', 'phone_off.png'), 216, 216);
// masters (with beam + big screen), per theme
const MVB = '20 -14 350 270';
for (const [t, th] of Object.entries(THEMES)) {
  const svg = doc(MVB, monitor(322, 34, th.accent) + hero({ mood: 'idle', accent: th.accent, beam: true, beamTo: [286, 44] }));
  writeFileSync(join(PUB, 'svg', `master_${t}.svg`), svg);
  png(`<div style="background:${th.bg}">${svg.replace('<svg ', '<svg width="1050" height="810" ')}</div>`, join(PUB, `master_${t}.png`), 1050, 810);
}
// icons
for (const s of ICON_SIZES) {
  writeFileSync(join(PUB, 'icon', `icon_${s}.svg`), iconSvg(s));
  png(iconSvg(s), join(PUB, 'icon', `icon_${s}.png`), s, s);
}
writeFileSync(join(PUB, 'icon', 'icon_1024.svg'), iconSvg(256).replace('width="256" height="256"', 'width="1024" height="1024"'));

// ---------------------------------------------------------------- app.ico (PNG entries, Vista+)
const blobs = ICON_SIZES.map((s) => readFileSync(join(PUB, 'icon', `icon_${s}.png`)));
const head = Buffer.alloc(6 + 16 * blobs.length);
head.writeUInt16LE(0, 0); head.writeUInt16LE(1, 2); head.writeUInt16LE(blobs.length, 4);
let off = head.length;
ICON_SIZES.forEach((s, i) => {
  const e = 6 + 16 * i;
  head.writeUInt8(s >= 256 ? 0 : s, e); head.writeUInt8(s >= 256 ? 0 : s, e + 1);
  head.writeUInt8(0, e + 2); head.writeUInt8(0, e + 3);
  head.writeUInt16LE(1, e + 4); head.writeUInt16LE(32, e + 6);
  head.writeUInt32LE(blobs[i].length, e + 8); head.writeUInt32LE(off, e + 12);
  off += blobs[i].length;
});
writeFileSync(join(ROOT, 'app/res/app.ico'), Buffer.concat([head, ...blobs]));

// ---------------------------------------------------------------- reference sheet
const cell = (m) => `<div style="display:inline-block;margin:6px;text-align:center;color:#8a7672;font-size:13px"><div style="background:${S.bg};border-radius:14px">${doc(EXPR_VB, hero({ mood: m, accent: S.accent }), 248, 212)}</div>${m}</div>`;
const themeCell = ([t, th]) => `<div style="display:inline-block;margin:6px;text-align:center;color:#8a7672;font-size:13px"><div style="background:${th.bg};border-radius:14px">${doc(MVB, monitor(322, 34, th.accent) + hero({ mood: 'idle', accent: th.accent, beam: true, beamTo: [286, 44] }), 300, 231)}</div>${t} ${th.accent}</div>`;
const icons = `<div style="display:inline-flex;align-items:flex-end;gap:14px;padding:14px;background:#202020;border-radius:14px;margin:6px">${[256, 64, 48, 40, 32, 24, 20, 16].map((s) => `<img src="${svgUri(iconSvg(s))}" width="${s}" height="${s}">`).join('')}</div>
  <div style="display:inline-flex;align-items:flex-end;gap:14px;padding:14px;background:#F3F3F3;border-radius:14px;margin:6px">${[64, 48, 32, 24, 16].map((s) => `<img src="${svgUri(iconSvg(s))}" width="${s}" height="${s}">`).join('')}</div>`;
renderHtml(page(`<div style="padding:18px 22px;width:1880px;background:#F6F0EC">
  <div style="font-size:34px;font-weight:800;color:#3b2a2e">投投 Toutou — 定稿（方向 A 軟綿光暈 · 圖示 C 幾何構成）</div>
  <div style="font-size:16px;color:#7a6662;margin:6px 0 10px">原創向量 · 雲朵本體白/奶油色，主題色只在手機螢幕、邊緣反光、光帶、愛心 · App 內以分層 PNG + Direct2D 程序化光帶/手機繪製</div>
  <div>${MOODS.map(cell).join('')}</div>
  <div>${Object.entries(THEMES).map(themeCell).join('')}</div>
  <div>${icons}</div></div>`, '#F6F0EC'), join(here, 'final.png'), 1924, 930, 1);
console.log('exported', W, 'x', H, 'layers');

// ---------------------------------------------------------------- tutorial mascot (docs/tutorial, base64 in CSS)
// <= 60 KB, full colour (quantizing posterizes the soft shading), no ground shadow (any page colour)
const TVB = '46 42 202 150';
png(doc(TVB, hero({ mood: 'idle', accent: S.accent, fx: false, shadow: false }), 340, 252), join(PUB, 'toutou_340.png'), 340, 252);
